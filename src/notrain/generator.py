"""Generate a robots.txt from a per-classification policy.

A policy maps each classification (``training`` / ``search`` /
``user-fetch``) to allowed (True) or blocked (False). Classifications
not mentioned default to allowed. Every crawler gets its own explicit
group, so parsing the generated file reproduces the intended verdict
for every crawler in the database (the round-trip property the test
suite checks).
"""
from __future__ import annotations

from collections.abc import Iterable

from .crawlers import CLASSIFICATIONS, CRAWLERS


def policy_from_lists(block: Iterable[str] = (),
                      allow: Iterable[str] = ()) -> dict[str, bool]:
    """Build a policy dict from block/allow classification names."""
    policy: dict[str, bool] = {}
    for name in block:
        _check(name)
        policy[name] = False
    for name in allow:
        _check(name)
        if name in policy and not policy[name]:
            raise ValueError(
                f"classification {name!r} is both blocked and allowed")
        policy[name] = True
    return policy


def _check(name: str) -> None:
    if name not in CLASSIFICATIONS:
        raise ValueError(
            f"unknown classification {name!r}; "
            f"expected one of {', '.join(CLASSIFICATIONS)}")


def generate_robots(policy: dict[str, bool], path: str = "/") -> str:
    for name in policy:
        _check(name)
    if not path.startswith("/"):
        path = "/" + path

    lines = [
        "# Generated by notrain (Tytechlabs) -- AI crawler policy",
        "# robots.txt is advisory: well-behaved crawlers honour it,",
        "# others may not. See README for honest limits.",
        "",
    ]
    for classification in CLASSIFICATIONS:
        allowed = policy.get(classification, True)
        members = [c for c in CRAWLERS if c.classification == classification]
        if not members:
            continue
        lines.append(f"# {classification}: {'allow' if allowed else 'BLOCK'}")
        for crawler in members:
            lines.append(f"User-agent: {crawler.token}")
            if allowed:
                lines.append(f"Allow: {path}")
            else:
                lines.append(f"Disallow: {path}")
            lines.append("")
    lines.append("User-agent: *")
    lines.append(f"Allow: {path}")
    lines.append("")
    return "\n".join(lines)
